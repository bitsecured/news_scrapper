def wait_for_human(driver, name):
    start = time.time()

    # Stronger indicators of an actual verification page
    body_markers = [
        "are you a robot",
        "verify you are human",
        "verifying you are human",
        "unusual traffic",
        "press & hold",
        "checking your browser",
        "cf-challenge",
        "access denied",
    ]

    log.info("[%s] Checking browser verification status...", name)

    while time.time() - start < HUMAN_WAIT_TIMEOUT:
        try:
            title = (driver.title or "").lower()
            url = (driver.current_url or "").lower()
            soup = BeautifulSoup(driver.page_source, "lxml")
            body = soup.get_text(" ", strip=True).lower()

            title_challenge = any(
                marker in title for marker in CHALLENGE_MARKERS
            )
            url_challenge = any(
                marker in url for marker in CHALLENGE_MARKERS
            )
            body_matches = [
                marker for marker in body_markers if marker in body
            ]

            # Require multiple body indicators to reduce false positives.
            challenge = (
                title_challenge
                or url_challenge
                or len(body_matches) >= 2
            )

            if not challenge:
                log.info(
                    "[%s] Verification appears complete. Title: %s | URL: %s",
                    name, driver.title, driver.current_url
                )
                return

            log.warning(
                "[%s] Verification still detected. Title: %s | URL: %s | "
                "Body indicators: %s",
                name, driver.title, driver.current_url, body_matches
            )

        except Exception as e:
            log.debug("[%s] Browser status check failed: %s", name, e)

        time.sleep(3)

    raise TimeoutError(
        f"{name}: Verification did not finish within "
        f"{HUMAN_WAIT_TIMEOUT} seconds"
    )



def browser_fetch_text(driver, url):
    """Download a text file (e.g. sitemap) from inside the verified browser session."""
    js = ("const cb = arguments[arguments.length-1];"
          "fetch(arguments[0], {credentials:'include'})"
          ".then(r => r.ok ? r.text() : null).then(cb).catch(() => cb(null));")
    try:
        driver.set_script_timeout(60)
        txt = driver.execute_async_script(js, url)
        return txt.encode("utf-8") if txt else None
    except Exception:
        return None


class SimpleFetcher:
    """Category 1: plain requests (through the rotating proxy)."""
    USE_PROXY = True

    def __init__(self, cfg):
        self.name = cfg["name"]
        self.session = make_session(use_proxy=self.USE_PROXY and not cfg.get("no_proxy", False))

    def get(self, url):
        try:
            r = self.session.get(url, timeout=40)
            return None if is_challenge(r.text, r.status_code) else r.text
        except requests.RequestException:
            return None

    def get_raw(self, url):
        try:
            r = self.session.get(url, timeout=30)
            return r.content if r.status_code == 200 else None
        except requests.RequestException:
            return None

    def close(self):
        self.session.close()


class CaptchaFetcher(SimpleFetcher):
    """Category 2: human verifies once in Chrome, cookies reused with requests."""
    USE_PROXY = False        # cookies are bound to your real IP

    def __init__(self, cfg):
        super().__init__(cfg)
        self.driver = make_driver()
        self.driver.get(cfg["root"])
        wait_for_human(self.driver, self.name)
        self._sync()

    def _sync(self):
        for c in self.driver.get_cookies():
            self.session.cookies.set(c["name"], c["value"], domain=c.get("domain"))

    def get(self, url):
        html = super().get(url)
        if html:
            return html
        self.driver.get(url)                         # challenge is back -> human again
        wait_for_human(self.driver, self.name)
        self._sync()
        return self.driver.page_source

    def get_raw(self, url):
        return super().get_raw(url) or browser_fetch_text(self.driver, url)

    def close(self):
        super().close()
        self.driver.quit()


class ContinuousFetcher:
    """Category 3: every page in a real browser; pause on every challenge."""
    def __init__(self, cfg):
        self.name = cfg["name"]
        self.driver = make_driver(use_proxy=cfg.get("use_proxy", False))
        self.driver.get(cfg["root"])
        wait_for_human(self.driver, self.name)

    def get(self, url):
        try:
            self.driver.get(url)
            time.sleep(random.uniform(2, 4))
            wait_for_human(self.driver, self.name)
            return self.driver.page_source
        except Exception as e:
            log.warning("[%s] browser error on %s: %s", self.name, url, e)
            return None

    def get_raw(self, url):
        return browser_fetch_text(self.driver, url)

    def close(self):
        self.driver.quit()


FETCHERS = {"simple": SimpleFetcher, "captcha": CaptchaFetcher,
            "continuous": ContinuousFetcher}


def parse_page(html):
    """Extract fields from an article page (JSON-LD first, then meta tags)."""
    soup = BeautifulSoup(html, "lxml")
    out = {f: "" for f in FIELDS}

    def author_str(a):
        if isinstance(a, str):
            return a
        if isinstance(a, dict):
            return str(a.get("name", ""))
        if isinstance(a, list):
            return ", ".join(filter(None, (author_str(x) for x in a)))
        return ""

    for tag in soup.find_all("script", type="application/ld+json"):
        try:
            data = json.loads(tag.string or "")
        except Exception:
            continue
        items = data if isinstance(data, list) else (
            data.get("@graph", [data]) if isinstance(data, dict) else [])
        for it in items:
            if isinstance(it, dict) and "Article" in str(it.get("@type", "")):
                out["title"] = out["title"] or str(it.get("headline", ""))
                out["description"] = out["description"] or str(it.get("description", ""))
                out["date_of_publication"] = out["date_of_publication"] or fmt_date(
                    str(it.get("datePublished", "")))
                out["author_name"] = out["author_name"] or author_str(it.get("author"))

    def meta(*names):
        for n in names:
            el = soup.find("meta", attrs={"property": n}) or soup.find("meta", attrs={"name": n})
            if el and el.get("content"):
                return el["content"].strip()
        return ""

    out["title"] = out["title"] or meta("og:title", "twitter:title") or (
        soup.title.string.strip() if soup.title and soup.title.string else "")
    out["description"] = out["description"] or meta("og:description", "description")
    out["date_of_publication"] = out["date_of_publication"] or fmt_date(
        meta("article:published_time", "og:article:published_time", "datePublished", "pubdate",
             "date", "parsely-pub-date", "sailthru.date", "DC.date.issued", "dcterms.created",
             "publish-date", "publication_date"))
    if not out["date_of_publication"]:
        t = soup.find("time")
        if t:
            out["date_of_publication"] = fmt_date(t.get("datetime") or t.get_text(strip=True))
    out["author_name"] = out["author_name"] or meta("author", "article:author", "byl")
    return out


