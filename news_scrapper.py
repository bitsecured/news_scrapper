def db_connect():
    return psycopg2.connect(**DB_CONFIG)


def check_db():
    """Connect, make sure the table and columns exist and that id is auto-generated.
    Returns (ok, message)."""
    try:
        conn = db_connect()
    except Exception as e:
        return False, (f"cannot connect to PostgreSQL: {e}\n"
                       "  Check that PostgreSQL is running and that PGPASSWORD (and PGHOST, PGPORT, "
                       "PGDATABASE, PGUSER if they differ) are set in this terminal.")
    try:
        schema, table = DB_TABLE.split(".")
        with conn.cursor() as cur:
            cur.execute("SELECT column_name, column_default, is_identity "
                        "FROM information_schema.columns "
                        "WHERE table_schema = %s AND table_name = %s", (schema, table))
            info = {r[0]: r for r in cur.fetchall()}
            if not info:
                return False, f"table {DB_TABLE} not found in database '{DB_CONFIG['dbname']}'"
            missing = [c for c in DB_COLS.values() if c not in info]
            if missing:
                return False, (f"column(s) {missing} not found in {DB_TABLE}. The table has: "
                               f"{sorted(info)}. Fix DB_COLS at the top of the script.")
            if "id" in info and info["id"][1] is None and info["id"][2] != "YES":
                cur.execute(f"SELECT COALESCE(MAX(id), 0) + 1 FROM {DB_TABLE}")
                nxt = cur.fetchone()[0]
                return False, (f"column id has no default, so inserts would fail. Run this once "
                               f"in pgAdmin (it continues after your existing rows):\n"
                               f"  ALTER TABLE {DB_TABLE} ALTER COLUMN id ADD GENERATED BY "
                               f"DEFAULT AS IDENTITY (START WITH {nxt});")
            cur.execute(f"SELECT COUNT(*) FROM {DB_TABLE}")
            n = cur.fetchone()[0]
        return True, f"database OK: {n} rows already in {DB_TABLE}"
    except Exception as e:
        return False, f"database check failed: {e}"
    finally:
        conn.close()


def db_existing_urls():
    """All URLs already in the table (cleaned), so they are never scraped or inserted twice."""
    if not DB_ENABLED:
        return set()
    try:
        conn = db_connect()
    except Exception as e:
        log.warning("could not read existing URLs from the database: %s", e)
        return set()
    try:
        with conn.cursor() as cur:
            cur.execute(f'SELECT "{DB_COLS["url"]}" FROM {DB_TABLE}')
            return {clean_url(r[0]) for r in cur.fetchall() if r[0]}
    except Exception as e:
        log.warning("could not read existing URLs from the database: %s", e)
        return set()
    finally:
        conn.close()


def _db_text(v):
    return str(v or "").replace("\x00", "")      # PostgreSQL rejects NUL characters


def save_to_db(rows):
    """Insert rows into the table. A URL that is already there is skipped (checked with
    NOT EXISTS, so no unique constraint is needed). Returns how many rows were inserted."""
    if not DB_ENABLED or not rows:
        return 0
    data, seen = [], set()
    for r in rows:
        url = clean_url(_db_text(r.get("url")))
        if not url or url in seen:
            continue
        seen.add(url)
        data.append((_db_text(r.get("source")), url, _db_text(r.get("title")),
                     normalize_date(r.get("date_of_publication", "")) or None,   # "" -> NULL
                     _db_text(r.get("description"))))
    if not data:
        return 0
    c = DB_COLS
    sql = (f'INSERT INTO {DB_TABLE} ("{c["website"]}", "{c["url"]}", "{c["title"]}", '
           f'"{c["publish_date"]}", "{c["content"]}") '
           f'SELECT v.w, v.u, v.t, v.d::date, v.c FROM (VALUES %s) AS v(w, u, t, d, c) '
           f'WHERE NOT EXISTS (SELECT 1 FROM {DB_TABLE} x WHERE x."{c["url"]}" = v.u) '
           f'ON CONFLICT DO NOTHING')
    inserted = 0
    try:
        conn = db_connect()               # own connection: safe with multiprocessing
    except Exception as e:
        log.error("database connection failed, %d rows NOT saved to DB: %s", len(data), e)
        return 0
    try:
        for i in range(0, len(data), 1000):
            chunk = data[i:i + 1000]
            try:
                with conn.cursor() as cur:
                    execute_values(cur, sql, chunk, page_size=1000)
                    inserted += cur.rowcount
                conn.commit()
            except Exception as e:
                conn.rollback()
                log.error("database insert failed (%d rows skipped): %s", len(chunk), e)
    finally:
        conn.close()
    return inserted


def import_csvs_to_db():
    """One-off: copy every saved data/<source>.csv into PostgreSQL (already-present URLs are skipped)."""
    total = 0
    for cfg in SOURCES:
        path = os.path.join(OUTPUT_DIR, f"{cfg['name']}.csv")
        if not os.path.exists(path) or os.path.getsize(path) == 0:
            continue
        df = pd.read_csv(path, dtype=str).fillna("")
        df["source"] = cfg["name"]
        n = save_to_db(df.to_dict("records"))
        total += n
        log.info("[%s] %d of %d CSV rows were new and inserted into the database",
                 cfg["name"], n, len(df))
    log.info("import finished: %d new rows inserted", total)


